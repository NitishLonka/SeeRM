-- SeeRM schema (PostgreSQL 17)
-- See docs/low-level-design.md for the design rationale.
-- Re-runnable: drops and recreates all SeeRM objects. DO NOT run against data you want to keep.

BEGIN;

DROP VIEW  IF EXISTS v_customer_directory;
DROP TABLE IF EXISTS interactions;
DROP TABLE IF EXISTS tasks;
DROP TABLE IF EXISTS deals;
DROP TABLE IF EXISTS customers;
DROP FUNCTION IF EXISTS set_updated_at();

-- Keeps updated_at current on every UPDATE.
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- customers: one row per person registered via the "New Customer" form.
-- ---------------------------------------------------------------------------
CREATE TABLE customers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL CHECK (char_length(btrim(full_name)) >= 2),
    email         VARCHAR(254) NOT NULL CHECK (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
    phone         VARCHAR(15)  NOT NULL CHECK (phone ~ '^[0-9+\-\s()]{7,15}$'),
    account_type  VARCHAR(20)  NOT NULL DEFAULT 'individual'
                  CHECK (account_type IN ('individual', 'business')),
    company_name  VARCHAR(150),
    status        VARCHAR(20)  NOT NULL DEFAULT 'Lead'
                  CHECK (status IN ('Lead', 'Active', 'Inactive')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Email is unique regardless of case.
CREATE UNIQUE INDEX ux_customers_email_lower ON customers (lower(email));
-- Supports the dashboard search on name / company and status filters.
CREATE INDEX ix_customers_full_name_lower    ON customers (lower(full_name));
CREATE INDEX ix_customers_company_name_lower ON customers (lower(company_name));
CREATE INDEX ix_customers_status             ON customers (status);

CREATE TRIGGER trg_customers_updated_at
    BEFORE UPDATE ON customers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- deals: sales opportunities. Drives "Deal Value" and "Pipeline Revenue".
-- ---------------------------------------------------------------------------
CREATE TABLE deals (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          BIGINT        NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    title                VARCHAR(200)  NOT NULL CHECK (char_length(btrim(title)) >= 2),
    value                NUMERIC(12,2) NOT NULL CHECK (value >= 0),
    stage                VARCHAR(20)   NOT NULL DEFAULT 'prospecting'
                         CHECK (stage IN ('prospecting', 'qualification', 'proposal',
                                          'negotiation', 'won', 'lost')),
    expected_close_date  DATE,
    closed_at            TIMESTAMPTZ,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- A deal is closed exactly when it is won or lost.
    CONSTRAINT ck_deals_closed_at
        CHECK ((stage IN ('won', 'lost')) = (closed_at IS NOT NULL))
);

CREATE INDEX ix_deals_customer_id ON deals (customer_id);
CREATE INDEX ix_deals_stage       ON deals (stage);

CREATE TRIGGER trg_deals_updated_at
    BEFORE UPDATE ON deals
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- tasks: follow-ups. Drives "Tasks Completed" and "follow-ups due".
-- ---------------------------------------------------------------------------
CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT       NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    deal_id       BIGINT       REFERENCES deals (id) ON DELETE SET NULL,
    title         VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) >= 2),
    due_date      DATE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open', 'completed')),
    completed_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_tasks_completed_at
        CHECK ((status = 'completed') = (completed_at IS NOT NULL))
);

CREATE INDEX ix_tasks_customer_id     ON tasks (customer_id);
CREATE INDEX ix_tasks_deal_id         ON tasks (deal_id);
CREATE INDEX ix_tasks_status_due_date ON tasks (status, due_date);

CREATE TRIGGER trg_tasks_updated_at
    BEFORE UPDATE ON tasks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- interactions: calls / emails / meetings / notes. Drives "Last Contact".
-- ---------------------------------------------------------------------------
CREATE TABLE interactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT       NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    type          VARCHAR(20)  NOT NULL CHECK (type IN ('call', 'email', 'meeting', 'note')),
    summary       VARCHAR(500) NOT NULL,
    occurred_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_interactions_customer_occurred ON interactions (customer_id, occurred_at DESC);

CREATE TRIGGER trg_interactions_updated_at
    BEFORE UPDATE ON interactions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- v_customer_directory: one row per customer, shaped for the dashboard table.
--   deal_value      = sum of non-lost deals (open + won)
--   pipeline_value  = sum of open deals (not won / lost)
--   last_contact_at = most recent interaction
-- ---------------------------------------------------------------------------
CREATE VIEW v_customer_directory AS
SELECT
    c.id,
    c.full_name,
    c.company_name,
    c.account_type,
    c.status,
    COALESCE(d.deal_value, 0)     AS deal_value,
    COALESCE(d.pipeline_value, 0) AS pipeline_value,
    i.last_contact_at
FROM customers c
LEFT JOIN (
    SELECT customer_id,
           SUM(value) FILTER (WHERE stage <> 'lost')            AS deal_value,
           SUM(value) FILTER (WHERE stage NOT IN ('won','lost')) AS pipeline_value
    FROM deals
    GROUP BY customer_id
) d ON d.customer_id = c.id
LEFT JOIN (
    SELECT customer_id, MAX(occurred_at) AS last_contact_at
    FROM interactions
    GROUP BY customer_id
) i ON i.customer_id = c.id;

COMMIT;
