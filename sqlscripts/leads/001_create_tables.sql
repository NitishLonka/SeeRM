-- Leads service schema (PostgreSQL 17). Database: leads (postgres-leads pod).
-- See docs/microservices-leads-plan.md.
-- Re-runnable: drops and recreates all Leads objects. DO NOT run against data you want to keep.

BEGIN;

DROP TABLE IF EXISTS leads;
DROP FUNCTION IF EXISTS set_updated_at();

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- leads: prospects captured before they become customers.
-- converted_customer_id points at customers.id in the *Customer service* database.
-- It is deliberately NOT a foreign key: that table lives in another service's DB.
-- ---------------------------------------------------------------------------
CREATE TABLE leads (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name             VARCHAR(80)   NOT NULL CHECK (char_length(btrim(first_name)) >= 1),
    last_name              VARCHAR(80)   NOT NULL CHECK (char_length(btrim(last_name)) >= 1),
    email                  VARCHAR(254)  NOT NULL CHECK (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
    phone                  VARCHAR(15)   CHECK (phone ~ '^[0-9+\-\s()]{7,15}$'),
    company_name           VARCHAR(150),
    job_title              VARCHAR(120),
    source                 VARCHAR(20)   NOT NULL DEFAULT 'website'
                           CHECK (source IN ('website', 'referral', 'event', 'cold_call', 'social', 'other')),
    status                 VARCHAR(20)   NOT NULL DEFAULT 'New'
                           CHECK (status IN ('New', 'Contacted', 'Qualified', 'Unqualified', 'Converted')),
    score                  SMALLINT      NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
    estimated_value        NUMERIC(12,2) CHECK (estimated_value >= 0),
    notes                  VARCHAR(2000),
    converted_customer_id  BIGINT,
    converted_at           TIMESTAMPTZ,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- A lead is Converted exactly when it is linked to a customer.
    CONSTRAINT ck_leads_converted
        CHECK ((status = 'Converted') = (converted_customer_id IS NOT NULL AND converted_at IS NOT NULL))
);

-- One lead per email (case-insensitive); also keeps conversion idempotent.
CREATE UNIQUE INDEX ux_leads_email_lower ON leads (lower(email));
CREATE INDEX ix_leads_status     ON leads (status);
CREATE INDEX ix_leads_source     ON leads (source);
CREATE INDEX ix_leads_created_at ON leads (created_at DESC);

CREATE TRIGGER trg_leads_updated_at
    BEFORE UPDATE ON leads
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
