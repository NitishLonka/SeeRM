using System.Text;
using Microsoft.EntityFrameworkCore;
using SeeRM.Api.Domain;

namespace SeeRM.Api.Data;

/// <summary>
/// Maps to the existing schema created by sqlscripts/001_create_tables.sql (database-first;
/// no EF migrations). Column names are snake_case versions of the property names.
/// </summary>
public class SeeRmDbContext(DbContextOptions<SeeRmDbContext> options) : DbContext(options)
{
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Deal> Deals => Set<Deal>();
    public DbSet<TaskItem> Tasks => Set<TaskItem>();
    public DbSet<Interaction> Interactions => Set<Interaction>();

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<Customer>(e =>
        {
            e.ToTable("customers");
            e.Property(x => x.FullName).HasMaxLength(150);
            e.Property(x => x.Email).HasMaxLength(254);
            e.Property(x => x.Phone).HasMaxLength(15);
            e.Property(x => x.AccountType).HasMaxLength(20);
            e.Property(x => x.CompanyName).HasMaxLength(150);
            e.Property(x => x.Status).HasMaxLength(20);
        });

        b.Entity<Deal>(e =>
        {
            e.ToTable("deals");
            e.Property(x => x.Title).HasMaxLength(200);
            e.Property(x => x.Value).HasPrecision(12, 2);
            e.Property(x => x.Stage).HasMaxLength(20);
            e.HasOne(x => x.Customer).WithMany(c => c.Deals)
                .HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Cascade);
        });

        b.Entity<TaskItem>(e =>
        {
            e.ToTable("tasks");
            e.Property(x => x.Title).HasMaxLength(200);
            e.Property(x => x.Status).HasMaxLength(20);
            e.HasOne(x => x.Customer).WithMany(c => c.Tasks)
                .HasForeignKey(x => x.CustomerId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.Deal).WithMany()
                .HasForeignKey(x => x.DealId).OnDelete(DeleteBehavior.SetNull);
        });

        b.Entity<Interaction>(e =>
        {
            e.ToTable("interactions");
            e.Property(x => x.Type).HasMaxLength(20);
            e.Property(x => x.Summary).HasMaxLength(500);
        });

        foreach (var entity in b.Model.GetEntityTypes())
        {
            foreach (var prop in entity.GetProperties())
                prop.SetColumnName(ToSnakeCase(prop.Name));

            // Identity keys are generated by Postgres.
            entity.FindProperty("Id")?.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAdd;

            // created_at has a DB default; updated_at is maintained by a DB trigger.
            // Read both back after insert/update instead of sending them.
            var created = entity.FindProperty("CreatedAt");
            var updated = entity.FindProperty("UpdatedAt");
            if (created is not null)
            {
                created.SetDefaultValueSql("now()");
                created.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAdd;
            }
            if (updated is not null)
            {
                updated.SetDefaultValueSql("now()");
                updated.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAddOrUpdate;
            }
        }
    }

    private static string ToSnakeCase(string name)
    {
        var sb = new StringBuilder(name.Length + 8);
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsUpper(c) && i > 0) sb.Append('_');
            sb.Append(char.ToLowerInvariant(c));
        }
        return sb.ToString();
    }
}
